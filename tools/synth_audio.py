#!/usr/bin/env python3
"""Synthesises every PARLOR sound from scratch (no samples, no third-party audio).
Pure standard library. Output: 16-bit mono WAV, 44.1 kHz.
Usage: synth_audio.py <out_dir>
All sounds are original works generated by this script, so they need no licence entry
beyond "original, procedurally synthesised" in CREDITS.md."""
import math, random, struct, sys, wave, os

SR = 44100
TAU = 2 * math.pi
rnd = random.Random(1887)  # fixed seed: reproducible builds


def silence(sec): return [0.0] * int(sec * SR)


def write(path, s, peak=0.89):
    m = max(1e-9, max(abs(x) for x in s))
    g = peak / m
    # 5 ms fades guard against clicks at either end
    f = int(0.005 * SR)
    n = len(s)
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        out = bytearray()
        for i, x in enumerate(s):
            a = 1.0
            if i < f: a = i / f
            elif i > n - f: a = max(0.0, (n - i) / f)
            out += struct.pack("<h", int(max(-1, min(1, x * g * a)) * 32767))
        w.writeframes(bytes(out))


def mix(dst, src, at=0.0, gain=1.0):
    o = int(at * SR)
    if o + len(src) > len(dst): dst.extend([0.0] * (o + len(src) - len(dst)))
    for i, x in enumerate(src): dst[o + i] += x * gain
    return dst


def biquad(s, kind, f0, q=0.707):
    w0 = TAU * min(f0, SR * 0.45) / SR
    al = math.sin(w0) / (2 * q); c = math.cos(w0)
    if kind == "lp": b0, b1, b2 = (1 - c) / 2, 1 - c, (1 - c) / 2
    elif kind == "hp": b0, b1, b2 = (1 + c) / 2, -(1 + c), (1 + c) / 2
    else: b0, b1, b2 = al, 0.0, -al  # bp
    a0, a1, a2 = 1 + al, -2 * c, 1 - al
    b0 /= a0; b1 /= a0; b2 /= a0; a1 /= a0; a2 /= a0
    x1 = x2 = y1 = y2 = 0.0; out = []
    for x in s:
        y = b0 * x + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2
        x2, x1, y2, y1 = x1, x, y1, y
        out.append(y)
    return out


def noise(sec): return [rnd.uniform(-1, 1) for _ in range(int(sec * SR))]


def env_exp(s, tau, attack=0.002):
    a = int(attack * SR)
    return [x * (min(1.0, i / max(1, a))) * math.exp(-i / (tau * SR)) for i, x in enumerate(s)]


def partials(sec, freqs, amps, taus, vib=0.0):
    n = int(sec * SR); out = [0.0] * n
    for f, a, t in zip(freqs, amps, taus):
        ph = rnd.uniform(0, TAU); k = TAU * f / SR; d = 1.0 / (t * SR)
        for i in range(n):
            out[i] += a * math.exp(-i * d) * math.sin(ph + k * i * (1 + vib * math.sin(TAU * 5 * i / SR)))
    return out


def reverb(s, sec=1.2, wet=0.3):
    """Cheap Schroeder-style tail: four feedback combs."""
    out = list(s) + [0.0] * int(sec * SR)
    dry = list(out)
    for d_ms, fb in ((29.7, 0.77), (37.1, 0.74), (41.1, 0.71), (43.7, 0.69)):
        d = int(d_ms * SR / 1000); buf = [0.0] * d; j = 0
        for i in range(len(out)):
            y = buf[j]; buf[j] = dry[i] + y * fb; j = (j + 1) % d
            out[i] += y * wet * 0.25
    return out


# ---------- individual sounds ----------

def coin_chime(base=2150.0, sec=1.6):
    r = [1.0, 2.32, 3.87, 5.31, 6.9]
    s = partials(sec, [base * x for x in r], [1, .6, .42, .25, .12], [.55, .4, .28, .18, .1])
    mix(s, env_exp(biquad(noise(0.02), "hp", 5000), 0.004), 0, 0.5)
    return s


def coin_land():
    s = partials(0.5, [3100, 4720, 7150, 9300], [1, .7, .4, .25], [.09, .07, .05, .03])
    mix(s, env_exp(partials(0.2, [190, 310], [1, .5], [.03, .02]), 0.05), 0, 0.9)  # the wood answers
    for k, t in enumerate((0.07, 0.125, 0.165, 0.195)):  # coin wobble settling
        mix(s, partials(0.12, [3300 + 90 * k, 5100], [.5, .3], [.025, .02]), t, 0.5 * (0.7 ** k))
    return s


def trap_clack():
    s = env_exp(biquad(noise(0.25), "bp", 1400, 1.2), 0.02)
    mix(s, env_exp(partials(0.35, [92, 141, 233], [1, .6, .3], [.09, .06, .04]), 0.2), 0, 1.3)
    mix(s, env_exp(biquad(noise(0.1), "bp", 2600, 3), 0.012), 0.045, 0.6)  # latch
    return s


def trap_creak(sec=1.1):
    n = int(sec * SR); out = []; ph = 0.0
    for i in range(n):
        t = i / n
        f = 210 + 160 * t + 30 * math.sin(TAU * 9 * t) + 14 * math.sin(TAU * 31 * t)
        ph += TAU * f / SR
        stick = 0.5 + 0.5 * math.sin(TAU * (17 + 9 * t) * i / SR)  # stick-slip gating
        out.append(((ph / TAU) % 1.0 * 2 - 1) * stick * math.sin(math.pi * t) ** 0.6)
    return biquad(biquad(out, "bp", 900, 1.5), "lp", 3200)


def knock():
    s = env_exp(partials(0.3, [118, 176, 262, 410], [1, .8, .45, .2], [.06, .05, .035, .02]), 0.25)
    mix(s, env_exp(biquad(noise(0.03), "bp", 1900, 1.5), 0.006), 0, 0.5)
    return s


def whoosh(sec=0.7, f_a=400, f_b=3200):
    n = int(sec * SR); src = noise(sec); out = []; lp = 0.0
    for i in range(n):
        t = i / n; f = f_a + (f_b - f_a) * math.sin(math.pi * t)
        a = 1 - math.exp(-TAU * f / SR); lp += a * (src[i] - lp)
        out.append(lp * math.sin(math.pi * t) ** 1.5)
    return biquad(out, "hp", 180)


def shimmer(sec=1.6):
    s = silence(sec)
    for _ in range(46):
        f = rnd.choice([2093, 2349, 2637, 3136, 3520, 4186, 4699, 5274]) * rnd.uniform(0.995, 1.005)
        at = rnd.uniform(0, sec - 0.5) ** 1.0
        mix(s, partials(0.45, [f, f * 2.01], [1, .3], [.12, .07]), at, rnd.uniform(.25, .7) * (1 - at / sec * .6))
    return s


def clap():
    f = rnd.uniform(900, 2300)
    return env_exp(biquad(noise(0.06), "bp", f, rnd.uniform(1.0, 2.2)), rnd.uniform(0.006, 0.014), 0.0006)


def applause(sec=5.0, people=26, swell=True):
    s = silence(sec)
    for _ in range(people):
        t = rnd.uniform(0, 0.5); rate = rnd.uniform(0.17, 0.27); g = rnd.uniform(.35, 1)
        while t < sec - 0.1:
            x = t / sec
            a = (min(1, x * 4) * (1 - max(0, x - .7) / .3) ** 1.5) if swell else 1.0
            mix(s, clap(), t, g * a)
            t += rate * rnd.uniform(.88, 1.14)
    return biquad(reverb(s, 0.9, 0.5), "hp", 300)


def tick():
    return env_exp(partials(0.06, [1850, 2770], [1, .5], [.012, .008]), 0.03)


def poke_click():
    s = env_exp(partials(0.09, [1320, 1980, 2640], [1, .5, .25], [.03, .02, .012]), 0.05)
    mix(s, env_exp(biquad(noise(0.012), "hp", 3000), 0.003), 0, 0.4)
    return s


def wand_tap():
    s = env_exp(partials(0.14, [820, 1490, 2380], [1, .6, .3], [.02, .015, .01]), 0.08)
    mix(s, shimmer(0.9), 0.03, 0.55)
    return s


def card_flip():
    return env_exp(biquad(whoosh(0.16, 1500, 6000), "hp", 900), 0.07, 0.01)


def curtain(sec=2.2):
    s = whoosh(sec, 120, 700)
    return mix(s, env_exp(partials(0.5, [70, 105], [1, .5], [.15, .1]), 0.3), sec - 0.55, 0.8)


def bird():
    out = []
    for k in range(5):
        n = int(0.085 * SR); ph = 0.0
        for i in range(n):
            t = i / n; f = 2900 + 1500 * math.sin(math.pi * t) + 280 * k
            ph += TAU * f / SR; out.append(math.sin(ph) * math.sin(math.pi * t) ** 2)
        out += silence(0.035)
    return out


def note(f, sec, bright=1.0):
    """Music-box tine: pure fundamental + inharmonic sparkle, hard attack."""
    return partials(sec, [f, f * 2.0, f * 3.01, f * 5.43], [1, .32 * bright, .16 * bright, .09 * bright],
                    [sec * .42, sec * .28, sec * .16, sec * .06])


def midi(n): return 440.0 * 2 ** ((n - 69) / 12)


def music_loop():
    """Original 3/4 music-box waltz, 16 bars, D major, 132 bpm. Loops seamlessly (tails wrap around)."""
    beat = 60.0 / 132; bar = 3 * beat; total = 16 * bar
    chords = [(50, 57, 66), (50, 57, 66), (55, 59, 62), (55, 59, 62), (57, 61, 64), (57, 61, 67), (50, 57, 66), (50, 57, 66),
              (47, 54, 62), (47, 54, 62), (52, 55, 59), (52, 55, 59), (57, 61, 64), (57, 61, 67), (50, 57, 66), (50, 54, 57)]
    mel = [[(78, 1), (81, 1), (86, 1)], [(85, 1), (83, 1), (81, 1)], [(79, 1.5), (83, .5), (86, 1)], [(83, 2), (79, 1)],
           [(76, 1), (79, 1), (85, 1)], [(83, 1), (81, 1), (79, 1)], [(78, 1.5), (81, .5), (86, 1)], [(81, 3)],
           [(78, 1), (83, 1), (90, 1)], [(88, 1), (86, 1), (83, 1)], [(79, 1.5), (83, .5), (88, 1)], [(86, 2), (83, 1)],
           [(85, 1), (88, 1), (91, 1)], [(90, 1), (88, 1), (85, 1)], [(86, 1), (81, 1), (78, 1)], [(74, 3)]]
    n = int(total * SR); s = [0.0] * n

    def put(src, at, g):
        o = int(at * SR)
        for i, x in enumerate(src): s[(o + i) % n] += x * g  # wrap: seamless loop

    for b in range(16):
        t0 = b * bar; lo, mid, hi = chords[b]
        put(note(midi(lo), 1.6, .5), t0, .55)
        put(note(midi(mid + 12), .9, .7), t0 + beat, .28); put(note(midi(hi + 12), .9, .7), t0 + beat, .28)
        put(note(midi(mid + 12), .9, .7), t0 + 2 * beat, .24); put(note(midi(hi + 12), .9, .7), t0 + 2 * beat, .24)
        t = t0
        for m, d in mel[b]:
            put(note(midi(m), 1.3 + d * .3), t + rnd.uniform(-.004, .004), .5); t += d * beat
    return s


def fanfare():
    s = silence(1.6)
    for k, (m, at, d) in enumerate([(74, 0, .14), (78, .13, .14), (81, .26, .14), (86, .40, .9)]):
        n = int((d + .25) * SR); ph = 0.0; v = []
        for i in range(n):
            t = i / SR; f = midi(m) * (1 + .004 * math.sin(TAU * 5.5 * t))
            ph += TAU * f / SR
            x = sum(math.sin(ph * h) / h for h in range(1, 9))  # brassy saw-ish
            v.append(x * min(1, t / .02) * math.exp(-max(0, t - d) / .12))
        mix(s, biquad(v, "lp", 3400), at, .5)
        mix(s, note(midi(m + 12), .8), at, .35)
    return reverb(s, 0.8, 0.35)


def voice(pattern, pitch=165.0, speed=1.0):
    """Wordless 'magician-speak': glottal pulse train through two moving formants per syllable.
    pattern: list of (vowel, pitch_mult, dur). Captions carry the meaning."""
    V = {"a": (780, 1250), "e": (520, 1900), "i": (320, 2300), "o": (480, 880), "u": (340, 760)}
    out = []
    for vowel, pm, dur in pattern:
        if vowel == "-": out += silence(dur / speed); continue
        f1, f2 = V[vowel]; n = int(dur / speed * SR); ph = 0.0; src = []
        for i in range(n):
            t = i / n
            f = pitch * pm * (1 + .05 * math.sin(math.pi * t) - .06 * t + .012 * math.sin(TAU * 6 * i / SR))
            ph = (ph + f / SR) % 1.0
            g = (1 - ph) ** 2.2 - .3  # falling glottal pulse
            src.append(g + rnd.uniform(-.03, .03))
        a = biquad(src, "bp", f1, 5); b = biquad(src, "bp", f2, 7)
        for i in range(n):
            t = i / n
            e = min(1, t / .12) * min(1, (1 - t) / .22)
            out.append((a[i] + .55 * b[i]) * e)
        out += silence(0.028 / speed)
    return biquad(out, "hp", 140)


